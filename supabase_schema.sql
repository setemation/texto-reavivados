-- 1. Criar a tabela de comentários
CREATE TABLE IF NOT EXISTS commentaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author TEXT NOT NULL,          -- Nome do autor (ex: 'Spurgeon', 'Moody', 'Matthew Henry')
    book TEXT NOT NULL,            -- Livro (ex: 'Gênesis', 'João')
    chapter INTEGER NOT NULL,      -- Capítulo (ex: 1)
    verse INTEGER,                 -- Versículo (pode ser NULL se o comentário for sobre o capítulo inteiro)
    text TEXT NOT NULL,            -- O texto do comentário
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Criar índices para acelerar a busca por referências e autor
CREATE INDEX IF NOT EXISTS idx_commentaries_ref ON commentaries (book, chapter, verse);
CREATE INDEX IF NOT EXISTS idx_commentaries_author ON commentaries (author);

-- 3. Habilitar RLS (Row Level Security)
ALTER TABLE commentaries ENABLE ROW LEVEL SECURITY;

-- 4. Remover políticas antigas de comentários se existirem
DROP POLICY IF EXISTS "Leitura publica de comentarios" ON commentaries;
DROP POLICY IF EXISTS "Acesso total de comentarios" ON commentaries;

-- 5. Criar política de acesso total (leitura e escrita)
CREATE POLICY "Acesso total de comentarios" 
ON commentaries FOR ALL 
USING (true) 
WITH CHECK (true);

